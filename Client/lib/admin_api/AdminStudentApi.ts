import { useQuery } from '@tanstack/react-query';
import { api } from '../api/axios';
import { classService } from '@/lib/admin_api/AdminClassService';

// --- API FETCH FUNCTIONS ---

/**
 * Hits your backend: GET /api/v1/admin/student/:studentId
 */
const getStudentByIdAPI = async (studentId: string) => {
    if (!studentId) return null;
    const res = await api.get(`api/v1/admin/student/${studentId}`);
    return res.data.data;
};

// --- TANSTACK CUSTOM HOOKS ---

/**
 * Hook to fetch all classes using your existing classService
 */
export const useGetClasses = () => {
    return useQuery({
        queryKey: ['classes'],
        queryFn: classService.getAll,
    });
};

/**
 * Hook to fetch a single student by their Unique ID
 * It only runs when studentId has a value (enabled: !!studentId)
 */
export const useGetStudentById = (studentId: string) => {
    return useQuery({
        queryKey: ['student', studentId],
        queryFn: () => getStudentByIdAPI(studentId),
        enabled: !!studentId,
        retry: false, // Prevents multiple retries if student is not found
    });
};

export interface CreateStudentPayload {
    name: string;
    email: string;
    password?: string; // Often generated by backend or sent securely
    teacherId: string;
    classId: string;
    schoolId: string;
    principalId?: string; // If required by your backend schema
}

export const studentService = {
    create: async (payload: CreateStudentPayload) => {
        const { data } = await api.post("/api/v1/admin/student", payload);
        return data;
    },
};